"""Activity 1: onboard LLM deployments into API Management.

Renders every model definition in models/*.yaml into APIOps artifacts:
  * an APIM backend that points at the model endpoint
  * an APIM API (OpenAPI spec + policy) that only routes to that deployment
  * per-environment backend URL overrides used by `apiops publish`

Usage:  python 01-onboard-llm/onboard_llm.py
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

import yaml

ACTIVITY_DIR = Path(__file__).resolve().parent
REPO_ROOT = ACTIVITY_DIR.parent
MODELS_DIR = ACTIVITY_DIR / "models"
TEMPLATES_DIR = ACTIVITY_DIR / "templates"
ARTIFACTS_DIR = REPO_ROOT / "apim-artifacts"
ENVIRONMENTS_DIR = REPO_ROOT / "03-publish" / "environments"

# APIs and backends whose names start with this prefix are owned by this script.
PREFIX = "llm-"
NAME_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
DEPLOYMENT_PATTERN = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
REQUIRED_FIELDS = ("name", "displayName", "deployment", "endpoints")
OVERRIDES_HEADER = (
    "# GENERATED by 01-onboard-llm/onboard_llm.py from 01-onboard-llm/models/*.yaml.\n"
    "# Do not edit by hand: change the model definition and re-run the script.\n"
)


def api_id(model: dict) -> str:
    return f"{PREFIX}{model['name']}"


def backend_id(model: dict) -> str:
    return f"{PREFIX}{model['name']}-backend"


def backend_url(endpoint: str) -> str:
    return endpoint.rstrip("/") + "/openai"


def load_models() -> list[dict]:
    models = []
    for path in sorted(MODELS_DIR.glob("*.yaml")):
        model = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        missing = [field for field in REQUIRED_FIELDS if not model.get(field)]
        if missing:
            raise ValueError(f"{path.name}: missing {', '.join(missing)}")
        if not NAME_PATTERN.match(model["name"]):
            raise ValueError(f"{path.name}: name must be lowercase letters, digits and hyphens")
        if not DEPLOYMENT_PATTERN.match(model["deployment"]):
            raise ValueError(f"{path.name}: deployment may only contain letters, digits, '.', '_' and '-'")
        for environment, endpoint in model["endpoints"].items():
            if not str(endpoint).startswith("https://"):
                raise ValueError(f"{path.name}: endpoint for '{environment}' must use https")
        models.append(model)

    if not models:
        raise ValueError(f"No model definitions found in {MODELS_DIR}")
    if len({frozenset(model["endpoints"]) for model in models}) != 1:
        raise ValueError("Every model must define endpoints for the same set of environments")
    return models


def render_backend(model: dict) -> None:
    default_endpoint = next(iter(model["endpoints"].values()))
    write_json(
        ARTIFACTS_DIR / "backends" / backend_id(model) / "backendInformation.json",
        {
            "properties": {
                "description": f"{model['displayName']} model endpoint",
                "url": backend_url(default_endpoint),
                "protocol": "http",
            }
        },
    )


def render_api(model: dict) -> None:
    api_dir = ARTIFACTS_DIR / "apis" / api_id(model)
    write_json(
        api_dir / "apiInformation.json",
        {
            "properties": {
                "displayName": model["displayName"],
                "description": model.get("description", ""),
                "path": f"llm/{model['name']}/openai",
                "protocols": ["https"],
                "subscriptionRequired": True,
                # Lets Azure OpenAI SDKs pass the APIM subscription key as their api-key.
                "subscriptionKeyParameterNames": {"header": "api-key", "query": "subscription-key"},
            }
        },
    )

    spec = json.loads((TEMPLATES_DIR / "openai-chat-completions.json").read_text(encoding="utf-8"))
    spec["info"]["title"] = model["displayName"]
    write_json(api_dir / "specification.json", spec)

    policy = (TEMPLATES_DIR / "llm-api-policy.xml").read_text(encoding="utf-8")
    policy = policy.replace("__BACKEND_ID__", backend_id(model)).replace("__DEPLOYMENT__", model["deployment"])
    write_text(api_dir / "policy.xml", policy)


def render_overrides(models: list[dict]) -> None:
    for environment in models[0]["endpoints"]:
        overrides = {
            "backends": [
                {"name": backend_id(model), "properties": {"url": backend_url(model["endpoints"][environment])}}
                for model in models
            ]
        }
        write_text(
            ENVIRONMENTS_DIR / f"configuration.{environment}.yaml",
            OVERRIDES_HEADER + yaml.safe_dump(overrides, sort_keys=False),
        )


def prune(directory: Path, keep: set[str]) -> None:
    """Remove artifacts for models that were deleted from the catalog."""
    if not directory.exists():
        return
    for child in directory.iterdir():
        if child.is_dir() and child.name.startswith(PREFIX) and child.name not in keep:
            shutil.rmtree(child)
            print(f"Removed stale artifact {child.relative_to(REPO_ROOT)}")


def write_json(path: Path, payload: object) -> None:
    write_text(path, json.dumps(payload, indent=2) + "\n")


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def main() -> int:
    try:
        models = load_models()
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    for model in models:
        render_backend(model)
        render_api(model)
    prune(ARTIFACTS_DIR / "apis", {api_id(model) for model in models})
    prune(ARTIFACTS_DIR / "backends", {backend_id(model) for model in models})
    render_overrides(models)

    print(f"Onboarded {len(models)} model(s): {', '.join(api_id(model) for model in models)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
